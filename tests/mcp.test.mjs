import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import readline from 'node:readline';
import { fileURLToPath } from 'node:url';
import { Store } from '../src/store.mjs';
import { fixture, task, workerResult } from './helpers.mjs';

test('facts MCP advertises only read-only tools and refuses writes', async t => {
  const env = fixture(t);
  const store = new Store(env.run); env.dispose(() => store.close());
  const taskDirectory = path.join(env.run, 'tasks', 'T1'); fs.mkdirSync(taskDirectory, { recursive: true });
  const taskID = store.addTask(task());
  const [factID] = store.submitWorker(taskID, workerResult(env.workspace), taskDirectory, env.workspace);
  const child = spawn(process.execPath, ['--disable-warning=ExperimentalWarning', fileURLToPath(new URL('../src/mcp.mjs', import.meta.url)), '--run', env.run], { windowsHide: true, stdio: ['pipe', 'pipe', 'pipe'] });
  t.after(() => { child.stdin.end(); child.kill(); });
  const responses = new Map(); let sequence = 0;
  const lines = readline.createInterface({ input: child.stdout });
  lines.on('line', line => { const message = JSON.parse(line); responses.get(message.id)?.(message); responses.delete(message.id); });
  const request = (method, params = {}) => new Promise(resolve => { const id = ++sequence; responses.set(id, resolve); child.stdin.write(JSON.stringify({ jsonrpc: '2.0', id, method, params }) + '\n'); });
  const initialized = await request('initialize', { protocolVersion: '2024-11-05' });
  assert.equal(initialized.result.serverInfo.name, 'id2a-facts');
  const result = await request('tools/list');
  assert.equal(result.result.tools.length, 6);
  assert(result.result.tools.some(tool => tool.name === 'ledger_page'));
  assert(result.result.tools.every(tool => tool.annotations.readOnlyHint));
  const denied = await request('tools/call', { name: 'facts_write', arguments: {} });
  assert.equal(denied.result.isError, true);
  const searched = await request('tools/call', { name: 'facts_search', arguments: { query: '문서' } });
  assert.equal(searched.result.isError, undefined);
  const page = await request('tools/call', { name: 'ledger_page', arguments: { collection: 'facts', limit: 1 } });
  const pack = JSON.parse(page.result.content[0].text);
  assert.equal(pack.total, 1);
  assert.equal(pack.included, 1);
  assert.equal(pack.next_offset, null);
  const retrieved = await request('tools/call', { name: 'facts_get', arguments: { id: factID, snapshot: pack.snapshot } });
  assert.equal(JSON.parse(retrieved.result.content[0].text).id, factID);
  const invalidPage = await request('tools/call', { name: 'ledger_page', arguments: { collection: 'facts', offset: 1 } });
  assert.equal(invalidPage.result.isError, true);
  store.db.prepare("UPDATE facts SET state='refuted' WHERE id=?").run(factID);
  const changed = await request('tools/call', { name: 'ledger_page', arguments: { collection: 'facts', snapshot: pack.snapshot } });
  assert.equal(changed.result.isError, true);
  const changedFact = await request('tools/call', { name: 'facts_get', arguments: { id: factID, snapshot: pack.snapshot } });
  assert.equal(changedFact.result.isError, true);
  const source = await request('tools/call', { name: 'workspace_read', arguments: { path: 'notes.txt' } });
  assert.equal(source.result.isError, undefined);
  assert.match(JSON.parse(source.result.content[0].text).text, /Node.js 24/u);
  const fact = store.fact(factID);
  const evidence = await request('tools/call', { name: 'evidence_read', arguments: { fact_id: factID, sha256: fact.evidence[0].sha256 } });
  assert.equal(evidence.result.isError, undefined);
  assert.match(JSON.parse(evidence.result.content[0].text).text, /Node.js 24/u);
  const unknownEvidence = await request('tools/call', { name: 'evidence_read', arguments: { fact_id: factID, sha256: '0'.repeat(64) } });
  assert.equal(unknownEvidence.result.isError, true);
  const outside = await request('tools/call', { name: 'workspace_read', arguments: { path: '../runs/' + env.run.split(/[\\/]/u).at(-1) + '/run.json' } });
  assert.equal(outside.result.isError, true);
  const closed = new Promise(resolve => child.once('close', resolve));
  child.stdin.end(); await closed; lines.close();
  assert.equal(store.listFacts().length, 1);
});
